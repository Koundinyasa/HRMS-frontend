import { NavLink } from "react-router-dom";
import { Wallet, Bell, Mail, Building2 } from "lucide-react";

const tabs = [
  { label: "Payroll", path: "payroll", icon: Wallet },
  { label: "Reminder", path: "reminder", icon: Bell },
  { label: "Email", path: "email", icon: Mail },
  { label: "Tenant", path: "tenant", icon: Building2 },
];

export default function SettingsTabs() {
  return (
    <div
      className="mb-5 w-full rounded-2xl px-3 py-2.5"
      style={{
        backgroundColor: "#F3F0FF",
        border: "1px solid #E9E5FF",
      }}
    >
      <div className="flex items-center gap-2 overflow-x-auto scrollbar-hide">
        {tabs.map((tab) => {
          const Icon = tab.icon;

          return (
            <NavLink
              key={tab.label}
              to={tab.path}
              className="flex h-9 shrink-0 items-center gap-1.5 rounded-lg px-3.5 text-[13px] font-medium whitespace-nowrap transition-all"
              style={({ isActive }) =>
                isActive
                  ? {
                      backgroundColor: "#FFFFFF",
                      border: "1px solid #7C3AED",
                      color: "#7C3AED",
                      fontWeight: 600,
                    }
                  : {
                      backgroundColor: "transparent",
                      border: "1px solid transparent",
                      color: "#64748B",
                    }
              }
            >
              {({ isActive }) => (
                <>
                  <Icon
                    size={15}
                    strokeWidth={isActive ? 2 : 1.7}
                    color={isActive ? "#7C3AED" : "#94A3B8"}
                  />
                  <span>{tab.label}</span>
                </>
              )}
            </NavLink>
          );
        })}
      </div>
    </div>
  );
}